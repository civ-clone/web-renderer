// One headless arena game: some seats played by the baseline `simple-ai-client`, the others by the candidate.
//
// Bundled by `tools/arena.js`, which copies both variants (git refs or directories) into a scratch directory and
// generates the `arena:variants` module this imports. Both copies of the AI share one copy of everything else, so they
// play the same game with the same classes; see docs/arena.md.
//
// It is `run.ts` with the AI seats swapped: same seeding, same plugin list (with the installed AI's line replaced by
// the two variants' `registerRules` and `registerStrategies`, in the same position), same stop at `turn:start`. That
// is what lets `--self-check` reproduce the conformance fixture's checksums.
//
// Emits one JSON document on stdout, between the markers below.

